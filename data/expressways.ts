export function getExpressway(id: string): Expressway | undefined {
  return expressways.find((e) => e.id === id)
}

/** Directions link that opens in the Google Maps app on phones. */
export function googleMapsDirectionsUrl(e: Expressway): string {
  const [origin, ...rest] = e.mapStops
  const destination = rest.pop() ?? origin
  const params = new URLSearchParams({ api: "1", origin, destination, travelmode: "driving" })
  if (rest.length) params.set("waypoints", rest.join("|"))
  return `https://www.google.com/maps/dir/?${params}`
}

/** Keyless embeddable route map (Google Maps legacy embed). */
export function googleMapsEmbedUrl(e: Expressway): string {
  const [origin, ...rest] = e.mapStops
  const daddr = rest.length ? rest.join(" to:") : origin
  return `https://maps.google.com/maps?saddr=${encodeURIComponent(origin)}&daddr=${encodeURIComponent(daddr).replace(/%20to%3A/g, "+to:")}&output=embed`
}

